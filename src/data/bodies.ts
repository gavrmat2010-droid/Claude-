export interface RingLook {
  /** inner/outer radius as multiples of the planet radius */
  inner: number;
  outer: number;
  color: string;
  opacity: number;
}

export interface Look {
  color: string;
  color2: string;
  /** continents / dark regions */
  spots?: string;
  /** horizontal cloud bands for gas giants */
  bands?: string[];
  /** a great storm */
  storm?: string;
  rings?: RingLook | null;
  scale?: number;
  alpha?: number;
  /** still accreting from the disk */
  forming?: boolean;
  /** surface is lava */
  molten?: boolean;
  /** deep-frozen around the white dwarf */
  frozen?: boolean;
}

export interface Era {
  /** years relative to today, inclusive start */
  from: number;
  title: string;
  text: string;
  look?: Partial<Look>;
  /** swallowed by the Sun — nothing left to draw */
  gone?: boolean;
}

export interface Body {
  id: string;
  name: string;
  kind: string;
  /** semi-major axis today, AU */
  orbitAU: number;
  periodYears: number;
  diameterKm: number;
  /** Earth = 1 */
  massEarth: number;
  dayHours: number;
  moons: number;
  /** mean surface temperature today, K */
  tempK: number;
  gravityG: number;
  /** baseline radius on screen, px */
  displayRadius: number;
  look: Look;
  description: string;
  facts: string[];
  eras: Era[];
}

